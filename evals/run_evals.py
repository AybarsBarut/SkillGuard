"""
SkillGuard Evaluation Runner: Automated Agent Behavior Scenarios (run_evals.py)
Validates expected verdicts (ALLOW / WARN / CONFIRM / BLOCK / BLOCK_PUSH)
and verifies that deterministic alert templates and rule IDs match expected behavior.
"""

import argparse
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR / "scripts"))

from scan_skill import scan_target
from sanitize_push import run_push_check


def execute_scenario(scenario: Dict[str, Any]) -> tuple[bool, str]:
    s_id = scenario["id"]
    t_type = scenario["target_type"]
    expected_verdict = scenario["expected_verdict"]
    required_rules = scenario.get("required_rules", [])

    if t_type == "text":
        result = scan_target(scenario["input"])
        actual_verdict = result["verdict"]
        matched_rules = {f["id"] for f in result["findings"]}
    elif t_type == "dir_fixture":
        fixture_path = ROOT_DIR / "tests" / "fixtures" / scenario["fixture_name"]
        result = scan_target(str(fixture_path))
        actual_verdict = result["verdict"]
        matched_rules = {f["id"] for f in result["findings"]}
    elif t_type == "push_env":
        with tempfile.TemporaryDirectory() as td:
            p = Path(td)
            (p / ".env").write_text("API_SECRET=super_secret_value\n", encoding="utf-8")
            res = run_push_check(workspace_root=p)
            actual_verdict = res["verdict"]
            matched_rules = {f["id"] for f in res["findings"]}
    elif t_type == "push_provenance":
        with tempfile.TemporaryDirectory() as td:
            p = Path(td)
            (p / "main.py").write_text("# Generated by Claude 3.5 Sonnet\ndef x(): pass\n", encoding="utf-8")
            res = run_push_check(workspace_root=p)
            actual_verdict = res["verdict"]
            matched_rules = {f["id"] for f in res["findings"]}
    else:
        return False, f"Unknown target_type '{t_type}'"

    # Evaluate verdict
    verdict_match = (actual_verdict == expected_verdict)
    # If ALLOW_WITH_NOTE is returned for ALLOW, accept it
    if expected_verdict == "ALLOW" and actual_verdict in ["ALLOW", "ALLOW_WITH_NOTE"]:
        verdict_match = True

    # Check required rules
    rules_matched = True
    missing_rules = []
    for r in required_rules:
        if r not in matched_rules:
            rules_matched = False
            missing_rules.append(r)

    success = verdict_match and rules_matched
    msg = f"Verdict: {actual_verdict} (expected {expected_verdict})"
    if missing_rules:
        msg += f" | Missing required rules: {missing_rules}"
    return success, msg


def run_all_evals() -> bool:
    scenarios_file = ROOT_DIR / "evals" / "scenarios.json"
    with open(scenarios_file, "r", encoding="utf-8") as f:
        scenarios = json.load(f)

    passed_count = 0
    total = len(scenarios)

    print(f"[SKILLGUARD] Evaluation Benchmark ({total} Scenarios)\n" + "=" * 60)
    for s in scenarios:
        ok, msg = execute_scenario(s)
        status = "[PASS]" if ok else "[FAIL]"
        if ok:
            passed_count += 1
        print(f"{status} [{s['id']}] {s['description']}")
        print(f"       {msg}")

    print("=" * 60)
    print(f"Final Score: {passed_count}/{total} Passed ({passed_count/total*100:.1f}%)")
    return passed_count == total


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass
    success = run_all_evals()
    sys.exit(0 if success else 1)
